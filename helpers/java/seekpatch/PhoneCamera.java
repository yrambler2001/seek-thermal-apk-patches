package seekpatch;

import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.ThreadFactory;

/**
 * seek-patch phone_camera: the phone's own rear camera runs only while Thermal+ is on.
 *
 * <p>The app opens the phone's camera with the live view and keeps its preview running in the plain
 * thermal view too, where nothing uses it: the picture is blended in only in Thermal+, and only
 * Thermal+ photos save it.  On a Pixel 8 Pro that preview kept the camera's HAL busy on more than a
 * CPU core, and an app with a camera open gets at most 60 Hz from the screen.
 *
 * <p>The patch takes the camera out of the render thread's start ({@link #ready}) and opens or
 * closes it when the stream turns Thermal+ on or off ({@link #thermalPlus}), on a thread of its own:
 * closing waits for the camera to be released.  The render thread does the opening and closing with
 * the camera handler's own methods ({@link Owner}, generated by the patch).
 */
public final class PhoneCamera {
    /** The live view's render thread. */
    public interface Owner {
        /** Start the camera's preview into the render thread's camera texture (opening the camera). */
        void seekpatchCameraOn();

        /** Stop the preview and release the camera. */
        void seekpatchCameraOff();
    }

    private static final ExecutorService CAMERA = Executors.newSingleThreadExecutor(new ThreadFactory() {
        @Override
        public Thread newThread(Runnable r) {
            Thread t = new Thread(r, "seekpatch.PhoneCamera");
            t.setDaemon(true);
            return t;
        }
    });
    private static Owner current;
    private static boolean open;

    private PhoneCamera() {
    }

    /** The render thread is set up, where it used to start the camera: the camera waits for Thermal+. */
    public static synchronized void ready(Owner owner) {
        current = owner;
        open = false;
    }

    /** The stream turns Thermal+ on or off; renderer is its render thread (null before it has one). */
    public static synchronized void thermalPlus(Object renderer, final boolean on) {
        if (!(renderer instanceof Owner)) {
            return;
        }
        final Owner owner = (Owner) renderer;
        if (owner != current) {
            current = owner;
            open = false;
        }
        if (on == open) {
            return;
        }
        open = on;
        CAMERA.execute(new Runnable() {
            @Override
            public void run() {
                try {
                    if (on) {
                        owner.seekpatchCameraOn();
                    } else {
                        owner.seekpatchCameraOff();
                    }
                } catch (RuntimeException e) {
                    // the camera handler reports its own errors; Thermal+ shows no camera picture
                }
            }
        });
    }

    /** The front / back camera switch: only while the camera is open. */
    public static synchronized boolean isOpen(Object renderer) {
        return open && renderer == current;
    }
}
