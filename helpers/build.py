#!/usr/bin/env python3
"""Compile the Java helpers (helpers/java) into the smali the patches add to the app
(src/seekpatch/helpers/*.smali).  The smali is committed, so patching needs no Android SDK;
run this after changing a helper (--check: is the committed smali up to date).

    javac (JDK 11+, Java 8 bytecode, against android.jar)  ->  d8 --release --min-api 23
        ->  classes.dex  ->  apktool d (the pinned jar seek-patch uses)  ->  smali

Needs the Android SDK pieces pinned below (ANDROID_HOME, or --sdk):
    sdkmanager "build-tools;35.0.0" "platforms;android-35"
helpers/stubs holds compile-only stand-ins for classes a patch generates (VideoConfig).
"""
from __future__ import annotations

import argparse
import filecmp
import glob
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "src"))

from seekpatch.toolchain import Toolchain, ToolchainError  # noqa: E402

BUILD_TOOLS = "35.0.0"
PLATFORM = "android-35"
MIN_API = 23  # the Seek app's minSdkVersion
OUT = os.path.join(REPO, "src", "seekpatch", "helpers")
HEADER = "# Generated by helpers/build.py from helpers/java -- do not edit.\n"


def sdk_root(arg: str | None) -> str:
    for root in (arg, os.environ.get("ANDROID_HOME"), os.environ.get("ANDROID_SDK_ROOT"),
                 "/opt/homebrew/share/android-commandlinetools"):
        if root and os.path.isdir(root):
            return root
    sys.exit("no Android SDK: set ANDROID_HOME or pass --sdk")


def run(cmd: list[str], env: dict | None = None) -> None:
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if r.returncode != 0:
        sys.exit(f"{os.path.basename(cmd[0])} failed:\n{r.stdout}{r.stderr}")


def build(sdk: str, out: str) -> list[str]:
    """Compile into `out`; returns the smali file names."""
    tc = Toolchain.load(download=True, log=lambda _: None)
    jdk = os.path.dirname(os.path.dirname(os.path.realpath(tc.java)))
    javac = os.path.join(jdk, "bin", "javac.exe" if os.name == "nt" else "javac")
    d8 = os.path.join(sdk, "build-tools", BUILD_TOOLS, "d8.bat" if os.name == "nt" else "d8")
    android_jar = os.path.join(sdk, "platforms", PLATFORM, "android.jar")
    for need, what in ((javac, "javac (install a JDK, not a JRE)"), (d8, f"build-tools;{BUILD_TOOLS}"),
                       (android_jar, f"platforms;{PLATFORM}")):
        if not os.path.exists(need):
            sys.exit(f"missing {what}: {need}")
    sources = sorted(glob.glob(os.path.join(HERE, "java", "seekpatch", "*.java")))
    stubs = sorted(glob.glob(os.path.join(HERE, "stubs", "seekpatch", "*.java")))
    stub_names = {os.path.splitext(os.path.basename(s))[0] for s in stubs}
    with tempfile.TemporaryDirectory(prefix="seek-patch-helpers-") as tmp:
        classes, dex, decoded = (os.path.join(tmp, d) for d in ("classes", "dex", "decoded"))
        os.makedirs(dex)
        run([javac, "-source", "8", "-target", "8", "-Xlint:-options", "-encoding", "UTF-8",
             "-bootclasspath", android_jar, "-d", classes, *sources, *stubs])
        compiled = sorted(p for p in glob.glob(os.path.join(classes, "seekpatch", "*.class"))
                          if os.path.basename(p).split("$")[0].removesuffix(".class") not in stub_names)
        run([d8, "--release", "--min-api", str(MIN_API), "--lib", android_jar, "--classpath", classes,
             "--output", dex, *compiled], env={**os.environ, "JAVA_HOME": jdk})
        apk = os.path.join(tmp, "helpers.apk")
        with zipfile.ZipFile(apk, "w") as z:
            z.write(os.path.join(dex, "classes.dex"), "classes.dex")
        tc.run_jar(tc.apktool, ["d", "-r", "-f", "-o", decoded, apk], "apktool decode")
        names = []
        for p in sorted(glob.glob(os.path.join(decoded, "smali", "seekpatch", "*.smali"))):
            with open(p, encoding="utf-8") as f:
                text = f.read()
            name = os.path.basename(p)
            with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(HEADER + text)
            names.append(name)
    return names


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sdk", help="Android SDK root (default: ANDROID_HOME)")
    ap.add_argument("--check", action="store_true", help="fail if the committed smali is not what the sources build")
    a = ap.parse_args()
    sdk = sdk_root(a.sdk)
    try:
        if not a.check:
            for old in glob.glob(os.path.join(OUT, "*.smali")):
                os.remove(old)
            names = build(sdk, OUT)
            print(f"wrote {len(names)} files to {os.path.relpath(OUT, REPO)}: {', '.join(names)}")
            return
        with tempfile.TemporaryDirectory(prefix="seek-patch-helpers-check-") as tmp:
            names = build(sdk, tmp)
            committed = sorted(os.path.basename(p) for p in glob.glob(os.path.join(OUT, "*.smali")))
            stale = sorted(set(names) ^ set(committed))
            stale += [n for n in names if n in committed and not filecmp.cmp(os.path.join(tmp, n), os.path.join(OUT, n), False)]
            if stale:
                sys.exit("helpers out of date (run helpers/build.py): " + ", ".join(sorted(set(stale))))
            print(f"helpers up to date ({len(names)} files)")
    except ToolchainError as e:
        sys.exit(str(e))
    finally:
        shutil.rmtree(os.path.join(HERE, "__pycache__"), ignore_errors=True)


if __name__ == "__main__":
    main()
